// ✂️ プレーンテキスト表示用の軽量クリーナー。
//
// AI 生成の提案（相談の明日からできる一歩 等）を行動リストに
// 取り込むと、Markdown の装飾記号（**太字** や 箇条書きの先頭記号）が本文に
// 混ざったまま保存されることがある。プレーンテキストとして描画する場所では
// これらの記号が「**6冊読んで…**」のように生で見えてしまうため、表示直前に
// そっと剥がす（保存データは触らない — 編集画面では原文のまま扱える）。
export function stripInlineMd(s) {
  if (!s || typeof s !== 'string') return s || '';
  return s
    .replace(/\*\*(.+?)\*\*/g, '$1') // **強調** → 中身だけ
    .replace(/\*\*/g, '')            // 対応の取れない ** の残骸
    .replace(/__(.+?)__/g, '$1')     // __強調__
    .replace(/^[-*・]\s+/, '')       // 行頭の箇条書き記号
    .trim();
}
