const ORDINALS = ['ひとつめ', 'ふたつめ', 'みっつめ', 'よっつめ', 'いつつめ', 'むっつめ', 'ななつめ', 'やっつめ', 'ここのつめ', 'とおめ'];

const COUNTER_RE = new RegExp(`[¥￥]?(\\d[\\d,]*)\\s*(${COUNTERS.map(([c]) => c).join('|')})`, 'g');

// 字幕の文 → 声に渡す かな まじりの文
export function toReading(text) {
  // 数の前後の半角の空きは読まない（「1 日」→「1日」）。言葉と言葉の間の空き（「アプリ orime」）は区切りとして残す
  let s = String(text || '').replace(/(?<=\d) (?=[^\x00-\x7F])/g, '').replace(/(?<=[^\x00-\x7F]) (?=[\d¥￥])/g, '');
  for (const [w, r] of WORDS) s = s.split(w).join(r);
  // ①②…は「ひとつめ、」（そのまま渡すと「① 1 年後」が「じゅういちねんご」と読まれた）
  s = s.replace(/([①-⑩])\s*/g, (_, c) => `${ORDINALS[c.charCodeAt(0) - 0x2460]}、`);
  s = s.replace(/p\.\s?(\d+)/g, (_, n) => `${numKana(Number(n))}ページ`);
  s = s.replace(/[¥￥](\d[\d,]*)/g, (_, n) => `${numKana(Number(n.replace(/,/g, '')))}えん`);
  // 「15 分後」の「後」は「ご」（「あと」と読ませない・2026-11-22）
  s = s.replace(COUNTER_RE, (_, n, c) => COUNTER_FN[c](Number(n.replace(/,/g, ''))));
  s = s.replace(/(ふん|ぷん|びょう|じかん|にち|か|しゅうかん|かげつ|さつ|かい)後/g, '$1ご');
  return s;
}

