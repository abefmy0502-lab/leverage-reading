//   1. 数と単位（助数詞）は、音の変わり方まで決めて かな にする（1 日＝いちにち・1 分＝いっぷん・1 冊＝いっさつ・1 か月＝いっかげつ …）
//   2. 読み違えやすい言葉は辞書で かな にする（積読＝つんどく・一行＝いちぎょう・何から＝なにから …）
//   3. 数字が 1 つでも残ったら、読みが決まっていない＝声を作らずに止める（unreadDigits・テストも同じ決まりで落ちる）
// 新しい単位・言葉が台本に入ってテストが落ちたら、下の COUNTERS か WORDS に 1 行足す。

const D = ['', 'いち', 'に', 'さん', 'よん', 'ご', 'ろく', 'なな', 'はち', 'きゅう'];

// 0〜99,999,999 を かな に（単位の前に付ける数）
export function numKana(n) {
  if (n === 0) return 'ゼロ';
  const under10k = (m) => {
    let out = '';
    const th = Math.floor(m / 1000); const h = Math.floor(m / 100) % 10; const t = Math.floor(m / 10) % 10; const o = m % 10;
    if (th) out += th === 1 ? 'せん' : th === 3 ? 'さんぜん' : th === 8 ? 'はっせん' : `${D[th]}せん`;
    if (h) out += h === 1 ? 'ひゃく' : h === 3 ? 'さんびゃく' : h === 6 ? 'ろっぴゃく' : h === 8 ? 'はっぴゃく' : `${D[h]}ひゃく`;
    if (t) out += `${t === 1 ? '' : D[t]}じゅう`;
    if (o) out += D[o];
    return out;
  };
  const man = Math.floor(n / 10000); const rest = n % 10000;
  return (man ? `${under10k(man)}まん` : '') + (rest ? under10k(rest) : '');
}

// 一の位で音が変わる単位: ones＝1〜9 のときの読み（そのまま全部）・ten＝10 の倍数の終わり（じゅっ〜）
const byLastDigit = (ones, ten) => (n) => {
  const last = n % 10;
  if (last) return `${n - last ? numKana(n - last) : ''}${ones[last - 1]}`;
  const tens = Math.floor(n / 10) % 10;
  const head = n - (n % 100);
  if (!tens) return `${numKana(n)}${ten.slice(3)}`; // 100・1000 などは数＋単位
  return `${head ? numKana(head) : ''}${tens === 1 ? '' : D[tens]}${ten}`;
};
const plain = (suffix, fix = {}) => (n) => fix[n] || `${numKana(n)}${suffix}`;

