const shelfRow = (y0, y1, seed) => {
  const out = [];
  let x = 58;
  let k = seed;
  while (x < 372) {
    const w = 18 + (k % 3) * 6;
    const top = y0 + 14 + (k % 4) * 10;
    out.push(`M${x} ${y1} L ${x} ${top} L ${x + w} ${top} L ${x + w} ${y1}`);
    x += w + 6;
    k += 1;
  }
  return P(out.join(' '));
};
