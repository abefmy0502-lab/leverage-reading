const clip = (s, n) => [...String(s ?? '').replace(/[\u0000-\u0008\u000b\u000c\u000e-\u001f\u007f]/g, ' ')].slice(0, n).join('');

/** AI に渡す本の書誌（公開の書誌だけ・長さを切る）。 */
export function bookFieldsUserText({ title = '', subtitle = '', author = '', publisher = '', description = '', toc = [], genreNames = [] } = {}) {
  const lines = [`書名: ${clip(title, 200)}${subtitle ? ` ${clip(subtitle, 120)}` : ''}`];
  if (author) lines.push(`著者: ${clip(author, 100)}`);
  if (publisher) lines.push(`出版社: ${clip(publisher, 60)}`);
  if (genreNames.length) lines.push(`ジャンル: ${genreNames.map((g) => clip(g, 30)).join(', ')}`);
  if (description) lines.push(`紹介文: ${clip(description, 800)}`);
  const t = (Array.isArray(toc) ? toc : []).slice(0, 25).map((l) => clip(l, 60)).filter(Boolean);
  if (t.length) lines.push(`目次: ${t.join(' / ')}`);
  // 書誌の中の </book> で枠を閉じられないように
  return `<book>${lines.join('\n').replace(/<\/?book>/gi, '')}</book>\nこの本の分野を JSON で答えてください。`;
}

